SELECT
'Invoice Distribution' AS SOURCE,
HCA.ACCOUNT_NUMBER,
HCA.ACCOUNT_NAME,
PROJ.SEGMENT1 AS PROJECT_NUMBER,
PROJ.NAME AS PROJECT_NAME,
TRUNC(XAH.ACCOUNTING_DATE, 'MM') AS GL_DATE,
GIR.PERIOD_NAME,
XAH.JE_CATEGORY_NAME,
GJB.NAME AS JOURNAL_BATCH_NAME,
GJB.DESCRIPTION AS JOURNAL_BATCH_DESCRIPTION,
GJB.POSTED_DATE BATCH_POSTED_DATE,
GJH.NAME AS JE_HEADER_NAME,
GJH.DESCRIPTION AS JE_HEADER_DESCRIPTION,
GJL.JE_LINE_NUM,
GJL.DESCRIPTION AS JE_LINE_DESCRIPTION,
FLV.MEANING AS ACCOUNTING_CLASS_NAME,
GLCC.SEGMENT1,
GLCC.SEGMENT2,
GLCC.SEGMENT3,
GLCC.SEGMENT4,
GLCC.SEGMENT5,
GLCC.SEGMENT6,
GLCC.SEGMENT7,
(GLCC.SEGMENT1 || '.' || GLCC.SEGMENT2 || '.' || GLCC.SEGMENT3 || '.' ||
    GLCC.SEGMENT4 || '.' || GLCC.SEGMENT5 || '.' || GLCC.SEGMENT6 || '.' || GLCC.SEGMENT7)
    AS ACCOUNTING_STRING,
SUM(NVL(XAL.ACCOUNTED_DR,0)) AS ACCOUNTED_DR,
SUM(NVL(XAL.ACCOUNTED_CR,0)) AS ACCOUNTED_CR,
OKC.CONTRACT_NUMBER
FROM XLA_AE_HEADERS XAH
INNER JOIN XLA_AE_LINES XAL
    ON XAL.AE_HEADER_ID = XAH.AE_HEADER_ID
INNER JOIN (
    SELECT XDL.AE_HEADER_ID,
           XDL.AE_LINE_NUM,
           MAX(GLD.CUSTOMER_TRX_ID) AS CUSTOMER_TRX_ID
    FROM XLA_DISTRIBUTION_LINKS XDL
    INNER JOIN RA_CUST_TRX_LINE_GL_DIST_ALL GLD
        ON GLD.CUST_TRX_LINE_GL_DIST_ID = XDL.SOURCE_DISTRIBUTION_ID_NUM_1
    WHERE XDL.APPLICATION_ID = 222
    AND XDL.SOURCE_DISTRIBUTION_TYPE = 'RA_CUST_TRX_LINE_GL_DIST_ALL'
    GROUP BY XDL.AE_HEADER_ID, XDL.AE_LINE_NUM
) TRX
    ON TRX.AE_HEADER_ID = XAL.AE_HEADER_ID
    AND TRX.AE_LINE_NUM = XAL.AE_LINE_NUM
INNER JOIN RA_CUSTOMER_TRX_ALL AR
    ON AR.CUSTOMER_TRX_ID = TRX.CUSTOMER_TRX_ID
INNER JOIN PJB_XLA_INV_HEAD_REF_V INV
    ON INV.INV_RA_CUST_TRX_ID = AR.CUSTOMER_TRX_ID
INNER JOIN GL_CODE_COMBINATIONS GLCC
    ON XAL.CODE_COMBINATION_ID = GLCC.CODE_COMBINATION_ID
LEFT JOIN HZ_CUST_ACCOUNTS HCA
    ON HCA.CUST_ACCOUNT_ID = AR.BILL_TO_CUSTOMER_ID
LEFT JOIN PJF_PROJECTS_ALL_VL PROJ
    ON PROJ.PROJECT_ID = INV.PROJECT_ID
LEFT JOIN (
    SELECT ID, MAX(CONTRACT_NUMBER) AS CONTRACT_NUMBER
    FROM OKC_K_HEADERS_ALL_B
    GROUP BY ID
) OKC
    ON OKC.ID = INV.CONTRACT_ID
LEFT JOIN FND_LOOKUP_VALUES_VL FLV
    ON FLV.LOOKUP_TYPE = 'XLA_ACCOUNTING_CLASS'
    AND FLV.LOOKUP_CODE = XAL.ACCOUNTING_CLASS_CODE
LEFT JOIN GL_IMPORT_REFERENCES GIR
    ON XAL.GL_SL_LINK_TABLE = GIR.GL_SL_LINK_TABLE
    AND XAL.GL_SL_LINK_ID = GIR.GL_SL_LINK_ID
LEFT JOIN GL_JE_BATCHES GJB
    ON GIR.JE_BATCH_ID = GJB.JE_BATCH_ID
LEFT JOIN GL_JE_HEADERS GJH
    ON GIR.JE_HEADER_ID = GJH.JE_HEADER_ID
LEFT JOIN GL_JE_LINES GJL
    ON GIR.JE_HEADER_ID = GJL.JE_HEADER_ID
    AND GIR.JE_LINE_NUM = GJL.JE_LINE_NUM
WHERE XAH.APPLICATION_ID = 222
AND TRUNC(XAH.ACCOUNTING_DATE) >= TRUNC(:P_startDate)
AND TRUNC(XAH.ACCOUNTING_DATE) < TRUNC(:P_endDate) + 1
GROUP BY
HCA.ACCOUNT_NUMBER,
HCA.ACCOUNT_NAME,
PROJ.SEGMENT1,
PROJ.NAME,
TRUNC(XAH.ACCOUNTING_DATE, 'MM'),
GIR.PERIOD_NAME,
XAH.JE_CATEGORY_NAME,
GJB.NAME,
GJB.DESCRIPTION,
GJB.POSTED_DATE,
GJH.NAME,
GJH.DESCRIPTION,
GJL.JE_LINE_NUM,
GJL.DESCRIPTION,
FLV.MEANING,
GLCC.SEGMENT1,
GLCC.SEGMENT2,
GLCC.SEGMENT3,
GLCC.SEGMENT4,
GLCC.SEGMENT5,
GLCC.SEGMENT6,
GLCC.SEGMENT7,
(GLCC.SEGMENT1 || '.' || GLCC.SEGMENT2 || '.' || GLCC.SEGMENT3 || '.' ||
    GLCC.SEGMENT4 || '.' || GLCC.SEGMENT5 || '.' || GLCC.SEGMENT6 || '.' || GLCC.SEGMENT7),
OKC.CONTRACT_NUMBER

UNION ALL

SELECT
'Revenue Distribution' AS SOURCE,
HCA.ACCOUNT_NUMBER,
HCA.ACCOUNT_NAME,
PROJ.SEGMENT1 AS PROJECT_NUMBER,
PROJ.NAME AS PROJECT_NAME,
TRUNC(XAH.ACCOUNTING_DATE, 'MM') AS GL_DATE,
GIR.PERIOD_NAME,
XAH.JE_CATEGORY_NAME,
GJB.NAME AS JOURNAL_BATCH_NAME,
GJB.DESCRIPTION AS JOURNAL_BATCH_DESCRIPTION,
GJB.POSTED_DATE BATCH_POSTED_DATE,
GJH.NAME AS JE_HEADER_NAME,
GJH.DESCRIPTION AS JE_HEADER_DESCRIPTION,
GJL.JE_LINE_NUM,
GJL.DESCRIPTION AS JE_LINE_DESCRIPTION,
FLV.MEANING AS ACCOUNTING_CLASS_NAME,
GLCC.SEGMENT1,
GLCC.SEGMENT2,
GLCC.SEGMENT3,
GLCC.SEGMENT4,
GLCC.SEGMENT5,
GLCC.SEGMENT6,
GLCC.SEGMENT7,
(GLCC.SEGMENT1 || '.' || GLCC.SEGMENT2 || '.' || GLCC.SEGMENT3 || '.' ||
    GLCC.SEGMENT4 || '.' || GLCC.SEGMENT5 || '.' || GLCC.SEGMENT6 || '.' || GLCC.SEGMENT7)
    AS ACCOUNTING_STRING,
SUM(NVL(XAL.ACCOUNTED_DR,0)) AS ACCOUNTED_DR,
SUM(NVL(XAL.ACCOUNTED_CR,0)) AS ACCOUNTED_CR,
OKC.CONTRACT_NUMBER
FROM PJB_XLA_REV_V PXR
INNER JOIN PJB_REV_DISTRIBUTIONS PRD
    ON PXR.REV_DISTRIBUTION_ID = PRD.REV_DISTRIBUTION_ID
INNER JOIN XLA_EVENTS XEV
    ON PRD.SLA_EVENT_ID = XEV.EVENT_ID
    AND XEV.EVENT_STATUS_CODE = 'P'
    AND XEV.PROCESS_STATUS_CODE = 'P'
INNER JOIN XLA_AE_HEADERS XAH
    ON XEV.EVENT_ID = XAH.EVENT_ID
INNER JOIN XLA_AE_LINES XAL
    ON XAH.AE_HEADER_ID = XAL.AE_HEADER_ID
INNER JOIN GL_CODE_COMBINATIONS GLCC
    ON XAL.CODE_COMBINATION_ID = GLCC.CODE_COMBINATION_ID
LEFT JOIN PJF_PROJECTS_ALL_VL PROJ
    ON PXR.LINKED_PROJECT_ID = PROJ.PROJECT_ID
LEFT JOIN FND_LOOKUP_VALUES_VL FLV
    ON FLV.LOOKUP_TYPE = 'XLA_ACCOUNTING_CLASS'
    AND FLV.LOOKUP_CODE = XAL.ACCOUNTING_CLASS_CODE
LEFT JOIN HZ_CUST_ACCOUNTS HCA
    ON PXR.CUSTOMER_ID = HCA.CUST_ACCOUNT_ID
LEFT JOIN GL_IMPORT_REFERENCES GIR
    ON XAL.GL_SL_LINK_TABLE = GIR.GL_SL_LINK_TABLE
    AND XAL.GL_SL_LINK_ID = GIR.GL_SL_LINK_ID
LEFT JOIN GL_JE_BATCHES GJB
    ON GIR.JE_BATCH_ID = GJB.JE_BATCH_ID
LEFT JOIN GL_JE_HEADERS GJH
    ON GIR.JE_HEADER_ID = GJH.JE_HEADER_ID
LEFT JOIN GL_JE_LINES GJL
    ON GIR.JE_HEADER_ID = GJL.JE_HEADER_ID
    AND GIR.JE_LINE_NUM = GJL.JE_LINE_NUM
LEFT JOIN OKC_K_HEADERS_ALL_B OKC
    ON OKC.ID = PXR.CONTRACT_ID
    AND OKC.MAJOR_VERSION = PXR.MAJOR_VERSION
WHERE TRUNC(XAH.ACCOUNTING_DATE) >= TRUNC(:P_startDate)
AND TRUNC(XAH.ACCOUNTING_DATE) < TRUNC(:P_endDate) + 1
GROUP BY
HCA.ACCOUNT_NUMBER,
HCA.ACCOUNT_NAME,
PROJ.SEGMENT1,
PROJ.NAME,
TRUNC(XAH.ACCOUNTING_DATE, 'MM'),
GIR.PERIOD_NAME,
XAH.JE_CATEGORY_NAME,
GJB.NAME,
GJB.DESCRIPTION,
GJB.POSTED_DATE,
GJH.NAME,
GJH.DESCRIPTION,
GJL.JE_LINE_NUM,
GJL.DESCRIPTION,
FLV.MEANING,
GLCC.SEGMENT1,
GLCC.SEGMENT2,
GLCC.SEGMENT3,
GLCC.SEGMENT4,
GLCC.SEGMENT5,
GLCC.SEGMENT6,
GLCC.SEGMENT7,
(GLCC.SEGMENT1 || '.' || GLCC.SEGMENT2 || '.' || GLCC.SEGMENT3 || '.' ||
    GLCC.SEGMENT4 || '.' || GLCC.SEGMENT5 || '.' || GLCC.SEGMENT6 || '.' || GLCC.SEGMENT7),
OKC.CONTRACT_NUMBER
